func TestInitIsDeterministicAndCheckIsReadOnly(t *testing.T) {
	release := fixtureRelease("1.2.3", 'a')
	firstRoot := t.TempDir()
	secondRoot := t.TempDir()
	firstResolver := &fakeResolver{latest: release}
	secondResolver := &fakeResolver{latest: release}
	first := Generator{Root: firstRoot, Resolver: firstResolver}
	second := Generator{Root: secondRoot, Resolver: secondResolver}

	firstSnapshot, err := first.Init(context.Background(), configuredFixture())
	if err != nil {
		t.Fatalf("first init: %v", err)
	}
	secondSnapshot, err := second.Init(context.Background(), configuredFixture())
	if err != nil {
		t.Fatalf("second init: %v", err)
	}
	if !reflect.DeepEqual(firstSnapshot.Files, secondSnapshot.Files) {
		t.Fatal("identical inputs generated different bytes")
	}
	before := captureTree(t, firstRoot)
	time.Sleep(10 * time.Millisecond)
	checked, err := first.Check()
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	after := captureTree(t, firstRoot)
	if !reflect.DeepEqual(before, after) {
		t.Fatalf("check modified the repository:\nbefore=%#v\nafter=%#v", before, after)
	}
	if !reflect.DeepEqual(checked.Files, firstSnapshot.Files) {
		t.Fatal("checked canonical bytes differ from generated bytes")
	}
	if _, err := os.Stat(filepath.Join(firstRoot, lockPath)); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("check created transaction state: %v", err)
	}
	if firstResolver.latestCalls != 1 || secondResolver.latestCalls != 1 {
		t.Fatalf("resolver calls = %d/%d, want 1/1", firstResolver.latestCalls, secondResolver.latestCalls)
	}
}

func TestInitRefusesEveryExistingTargetBeforeResolution(t *testing.T) {
	for _, relative := range targetPaths {
		t.Run(strings.ReplaceAll(relative, "/", "_"), func(t *testing.T) {
			root := t.TempDir()
			target := filepath.Join(root, filepath.FromSlash(relative))
			if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(target, []byte("owner data\n"), 0o600); err != nil {
				t.Fatal(err)
			}
			resolver := &fakeResolver{latest: fixtureRelease("1.2.3", 'a')}
			_, err := (Generator{Root: root, Resolver: resolver}).Init(context.Background(), DefaultConfig())
			assertErrorKind(t, err, ErrorCommittedData)
			if resolver.latestCalls != 0 {
				t.Fatalf("resolver called %d times before refusing existing target", resolver.latestCalls)
			}
		})
	}
}

func TestCheckRejectsDriftWithoutRepair(t *testing.T) {
	testCases := []struct {
		name     string
		relative string
		mutate   func([]byte) []byte
	}{
		{name: "posix script", relative: posixPath, mutate: appendMarker},
		{name: "Windows script", relative: windowsPath, mutate: appendMarker},
		{name: "unknown property", relative: propertiesPath, mutate: appendMarker},
		{
			name: "owner config",
			relative: configPath,
			mutate: func(raw []byte) []byte {
				return bytes.Replace(raw, []byte(`mode = "auto"`), []byte(`mode = "trial"`), 1)
			},
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			root := t.TempDir()
			generator := Generator{Root: root, Resolver: &fakeResolver{latest: fixtureRelease("1.2.3", 'a')}}
			if _, err := generator.Init(context.Background(), configuredFixture()); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(root, filepath.FromSlash(testCase.relative))
			raw, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			mutated := testCase.mutate(raw)
			if err := os.WriteFile(path, mutated, fileModes[testCase.relative]); err != nil {
				t.Fatal(err)
			}
			before := captureTree(t, root)
			_, err = generator.Check()
			assertErrorKind(t, err, ErrorCommittedData)
			if after := captureTree(t, root); !reflect.DeepEqual(before, after) {
				t.Fatal("failed check repaired or otherwise modified drift")
			}
		})
	}
}

func TestUpdatePreservesScriptsAndOwnerConfiguration(t *testing.T) {
	initial := fixtureRelease("1.2.3", 'a')
	next := fixtureRelease("1.3.0", 'b')
	resolver := &fakeResolver{
		latest: initial,
		versions: map[string]Release{
			"1.3.0": next,
		},
	}
	root := t.TempDir()
	generator := Generator{Root: root, Resolver: resolver}
	before, err := generator.Init(context.Background(), configuredFixture())
	if err != nil {
		t.Fatal(err)
	}
	originalTree := captureTree(t, root)
	old, updated, changed, err := generator.Update(context.Background(), "1.3.0", false)
	if err != nil {
		t.Fatalf("update: %v", err)
	}
	if !changed || old.Release.Version != "1.2.3" || updated.Release.Version != "1.3.0" {
		t.Fatalf("unexpected update result: changed=%t old=%s new=%s", changed, old.Release.Version, updated.Release.Version)
	}
	for _, relative := range []string{posixPath, windowsPath, configPath} {
		if !bytes.Equal(before.Files[relative], updated.Files[relative]) {
			t.Fatalf("update changed owner-controlled %s", relative)
		}
	}
	if bytes.Equal(before.Files[propertiesPath], updated.Files[propertiesPath]) {
		t.Fatal("update did not change distribution identity")
	}
	checked, err := generator.Check()
	if err != nil || checked.Release.Version != "1.3.0" {
		t.Fatalf("updated check = %s/%v", checked.Release.Version, err)
	}
	stable := captureTree(t, root)
	_, _, changed, err = generator.Update(context.Background(), "1.3.0", false)
	if err != nil || changed {
		t.Fatalf("same-version update = changed %t/error %v", changed, err)
	}
	if resolver.versionCalls != 1 {
		t.Fatalf("version resolver calls = %d, want 1", resolver.versionCalls)
	}
	if after := captureTree(t, root); !reflect.DeepEqual(stable, after) {
		t.Fatal("same-version update changed files")
	}
	if originalTree[configPath].digest != captureTree(t, root)[configPath].digest {
		t.Fatal("owner configuration digest changed")
	}
}

func TestDowngradeRequiresExplicitAuthority(t *testing.T) {
	initial := fixtureRelease("2.0.0", 'b')
	previous := fixtureRelease("1.9.9", 'a')
	resolver := &fakeResolver{
		latest: initial,
		versions: map[string]Release{
			"1.9.9": previous,
		},
	}
	root := t.TempDir()
	generator := Generator{Root: root, Resolver: resolver}
	if _, err := generator.Init(context.Background(), DefaultConfig()); err != nil {
		t.Fatal(err)
	}
	before := captureTree(t, root)
	_, _, _, err := generator.Update(context.Background(), "1.9.9", false)
	assertErrorKind(t, err, ErrorCommittedData)
	if resolver.versionCalls != 0 || !reflect.DeepEqual(before, captureTree(t, root)) {
		t.Fatal("rejected downgrade resolved metadata or changed files")
	}
	_, after, changed, err := generator.Update(context.Background(), "1.9.9", true)
	if err != nil || !changed || after.Release.Version != "1.9.9" {
		t.Fatalf("authorized downgrade = changed %t/version %s/error %v", changed, after.Release.Version, err)
	}
}

