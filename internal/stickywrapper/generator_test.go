type treeEntry struct {
	digest  [32]byte
	mode    fs.FileMode
	modTime time.Time
}

func captureTree(t *testing.T, root string) map[string]treeEntry {
	t.Helper()
	result := make(map[string]treeEntry)
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		result[filepath.ToSlash(relative)] = treeEntry{
			digest: sha256.Sum256(raw), mode: info.Mode().Perm(), modTime: info.ModTime(),
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return result
}

func appendMarker(raw []byte) []byte {
	return append(append([]byte(nil), raw...), []byte("owner drift\n")...)
}

func mustRead(t *testing.T, path string) []byte {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

func assertErrorKind(t *testing.T, err error, want ErrorKind) {
	t.Helper()
	var classifiedError *Error
	if !errors.As(err, &classifiedError) || classifiedError.Kind != want {
		t.Fatalf("error = %v, want kind %d", err, want)
	}
}

func assertNoTransactionResidue(t *testing.T, root string) {
	t.Helper()
	var residue []string
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if path == root {
			return nil
		}
		name := entry.Name()
		if name == lockPath || strings.HasPrefix(name, ".buildopt-wrapper-") {
			residue = append(residue, path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(residue)
	if len(residue) != 0 {
		t.Fatalf("transaction residue: %v", residue)
	}
}
