type fakeResolver struct {
	latest       Release
	versions     map[string]Release
	latestCalls  int
	versionCalls int
	err          error
}

func (resolver *fakeResolver) Latest(context.Context) (Release, error) {
	resolver.latestCalls++
	if resolver.err != nil {
		return Release{}, resolver.err
	}
	return resolver.latest, nil
}

func (resolver *fakeResolver) Version(_ context.Context, version string) (Release, error) {
	resolver.versionCalls++
	if resolver.err != nil {
		return Release{}, resolver.err
	}
	release, ok := resolver.versions[version]
	if !ok {
		return Release{}, errors.New("release not found")
	}
	return release, nil
}

