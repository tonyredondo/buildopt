func TestFailedPublicationRollsBackEveryTarget(t *testing.T) {
	initial := fixtureRelease("1.2.3", 'a')
	next := fixtureRelease("1.2.4", 'b')
	resolver := &fakeResolver{
		latest: initial,
		versions: map[string]Release{
			"1.2.4": next,
		},
	}
	root := t.TempDir()
	generator := Generator{Root: root, Resolver: resolver}
	if _, err := generator.Init(context.Background(), DefaultConfig()); err != nil {
		t.Fatal(err)
	}
	before := captureTree(t, root)
	renameCalls := 0
	failureInjected := false
	generator.rename = func(oldPath, newPath string) error {
		renameCalls++
		if renameCalls == 6 && !failureInjected {
			failureInjected = true
			return errors.New("injected publish failure")
		}
		return os.Rename(oldPath, newPath)
	}
	_, _, _, err := generator.Update(context.Background(), "1.2.4", false)
	assertErrorKind(t, err, ErrorInternal)
	if !failureInjected {
		t.Fatal("publication failure was not injected")
	}
	after := captureTree(t, root)
	if !reflect.DeepEqual(before, after) {
		t.Fatalf("failed publication left partial state:\nbefore=%#v\nafter=%#v", before, after)
	}
	assertNoTransactionResidue(t, root)
}

